// These auxiliary INFORMATION_SCHEMA tables are catalog shells. XMySQL does
// still leaves plugin-owned and FULLTEXT-specific catalog data to their
// respective optional subsystems, but durable InnoDB tablespace/file metadata
// and ANALYZE-backed column statistics are projected by dedicated handlers.

func informationSchemaAuxiliarySelect(query, table string, columns []string) *SelectResult {
	return newInformationSchemaSelectResult("information_schema."+table, requestedInformationSchemaColumns(query, columns), nil)
}

func (e *XMySQLExecutor) executeInformationSchemaColumnStatisticsSelect(query string) *SelectResult {
	const table = "column_statistics"
	columns := requestedInformationSchemaColumns(query, []string{
		"SCHEMA_NAME", "TABLE_NAME", "COLUMN_NAME", "HISTOGRAM",
	})
	if e == nil || e.infosSchemaManager == nil {
		return newInformationSchemaSelectResult("information_schema."+table, columns, nil)
	}

	filters := informationSchemaMetadataFilters(query)
	rows := make([][]interface{}, 0)
	for _, tableMeta := range e.scanFrmTables() {
		if !metadataPatternMatches(tableMeta.schemaName, filters["schema_name"]) ||
			!metadataPatternMatches(tableMeta.tableName, filters["table_name"]) {
			continue
		}
		stats, err := e.infosSchemaManager.GetTableStats(context.Background(), tableMeta.schemaName, tableMeta.tableName)
		if err != nil || stats == nil || stats.RowCount == 0 || len(stats.ColumnStats) == 0 {
			continue
		}

		columnNames := make([]string, 0, len(tableMeta.columns))
		for _, column := range tableMeta.columns {
			columnNames = append(columnNames, column.name)
		}
		for _, columnName := range columnNames {
			if !metadataPatternMatches(columnName, filters["column_name"]) {
				continue
			}
			stat, ok := informationSchemaColumnStat(stats.ColumnStats, columnName)
			if !ok || stat.HistogramDropped || stat.MinValue == nil || stat.MaxValue == nil {
				continue
			}
			histogram, err := informationSchemaHistogramJSON(stats.RowCount, stat)
			if err != nil {
				continue
			}
			values := map[string]interface{}{
				"SCHEMA_NAME": tableMeta.schemaName,
				"TABLE_NAME":  tableMeta.tableName,
				"COLUMN_NAME": columnName,
				"HISTOGRAM":   histogram,
			}
			if performanceSchemaLockValuesMatch(query, values) {
				rows = append(rows, projectInformationSchemaRow(columns, values))
			}
		}
	}
	sort.SliceStable(rows, func(i, j int) bool {
		return fmt.Sprint(rows[i]) < fmt.Sprint(rows[j])
	})
	return newInformationSchemaSelectResult("information_schema."+table, columns, rows)
}

func informationSchemaColumnStat(stats map[string]metadata.Stats, columnName string) (metadata.Stats, bool) {
	for name, stat := range stats {
		if strings.EqualFold(name, columnName) {
			return stat, true
		}
	}
	return metadata.Stats{}, false
}

// informationSchemaHistogramJSON prefers the explicitly persisted histogram
// generated by ANALYZE TABLE ... UPDATE HISTOGRAM. Older statistics sidecars
// only contain scalar min/max/NDV/null facts, so they retain the deterministic
// one-bucket fallback for backward compatibility.
func informationSchemaHistogramJSON(rowCount uint64, stat metadata.Stats) (string, error) {
	if rowCount == 0 {
		return "", fmt.Errorf("histogram row count is zero")
	}
	nullFraction := float64(stat.NullCount) / float64(rowCount)
	if nullFraction < 0 {
		nullFraction = 0
	}
	if nullFraction > 1 {
		nullFraction = 1
	}
	buckets := make([][]interface{}, 0)
	histogramType := "equi-height"
	samplingRate := 1.0
	numberOfBucketsSpecified := 1
	if stat.Histogram != nil && len(stat.Histogram.Buckets) > 0 {
		histogramType = stat.Histogram.HistogramType
		if histogramType == "" {
			histogramType = "equi-height"
		}
		if stat.Histogram.SamplingRate > 0 {
			samplingRate = stat.Histogram.SamplingRate
		}
		if stat.Histogram.NumberOfBucketsSpecified > 0 {
			numberOfBucketsSpecified = stat.Histogram.NumberOfBucketsSpecified
		}
		for _, bucket := range stat.Histogram.Buckets {
			cumulativeFrequency := bucket.CumulativeFrequency
			if cumulativeFrequency < 0 {
				cumulativeFrequency = 0
			}
			if cumulativeFrequency > 1 {
				cumulativeFrequency = 1
			}
			buckets = append(buckets, []interface{}{
				bucket.LowerBound,
				bucket.UpperBound,
				cumulativeFrequency,
				bucket.DistinctCount,
			})
		}
	}
	if len(buckets) == 0 {
		distinct := stat.DistinctCount
		if distinct == 0 {
			distinct = 1
		}
		buckets = append(buckets, []interface{}{stat.MinValue, stat.MaxValue, 1.0, distinct})
	}
	payload := map[string]interface{}{
		"buckets":                     buckets,
		"null-values":                 nullFraction,
		"sampling-rate":               samplingRate,
		"histogram-type":              histogramType,
		"number-of-buckets-specified": numberOfBucketsSpecified,
	}
	raw, err := json.Marshal(payload)
	if err != nil {
		return "", fmt.Errorf("marshal column histogram: %w", err)
	}
	return string(raw), nil
}

