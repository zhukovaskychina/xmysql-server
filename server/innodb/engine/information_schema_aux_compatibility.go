// executeInformationSchemaConnectionControlFailedLoginAttemptsSelect exposes
// the live consecutive authentication-failure counters captured at the
// protocol boundary. A successful login removes the account row.
func (e *XMySQLExecutor) executeInformationSchemaConnectionControlFailedLoginAttemptsSelect(query string) *SelectResult {
	const table = "connection_control_failed_login_attempts"
	columns := requestedInformationSchemaColumns(query, []string{"USERHOST", "FAILED_ATTEMPTS"})
	if e == nil || e.metricsRecorder == nil {
		return newInformationSchemaSelectResult("information_schema."+table, columns, nil)
	}
	rows := make([][]interface{}, 0)
	for _, attempt := range e.metricsRecorder.FailedLoginAttempts() {
		if !informationSchemaConnectionControlUserHostMatches(query, attempt.UserHost) ||
			!performanceSchemaSummaryFilterMatches(query, "failed_attempts", fmt.Sprint(attempt.FailedAttempts)) {
			continue
		}
		rows = append(rows, projectInformationSchemaRow(columns, map[string]interface{}{
			"USERHOST": attempt.UserHost, "FAILED_ATTEMPTS": attempt.FailedAttempts,
		}))
	}
	return newInformationSchemaSelectResult("information_schema."+table, columns, rows)
}

func informationSchemaConnectionControlUserHostMatches(query, value string) bool {
	pattern := regexp.MustCompile(`(?is)\buserhost\s*(=|like)\s*'((?:''|[^'])*)'`)
	match := pattern.FindStringSubmatch(query)
	if len(match) != 3 {
		return true
	}
	filter := strings.ReplaceAll(match[2], "''", "'")
	if strings.EqualFold(match[1], "=") {
		return strings.EqualFold(value, filter)
	}
	return performanceSchemaSQLLike(filter, value)
}
